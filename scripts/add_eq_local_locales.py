def load(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=OrderedDict)


def save(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")


def main():
    missing = [l for l in T if not os.path.exists(os.path.join(LOCALES_DIR, f"{l}.json"))]
    if missing:
        raise SystemExit(f"locale files missing: {missing}")

    # parity check: every locale must define the same key set
    en_keys = set(T["en"]["eq"]) | set(T["en"]["local"])
    for loc, groups in T.items():
        keys = set(groups["eq"]) | set(groups["local"])
        if keys != en_keys:
            diff = keys.symmetric_difference(en_keys)
            raise SystemExit(f"{loc} key mismatch: {diff}")

    for loc, groups in T.items():
        path = os.path.join(LOCALES_DIR, f"{loc}.json")
        data = load(path)

        player = data.setdefault("player", OrderedDict())
        eq = player.setdefault("equalizer", OrderedDict())
        for k, v in groups["eq"].items():
            eq[k] = v

        local = data.setdefault("local", OrderedDict())
        for k, v in groups["local"].items():
            local[k] = v

        common = data.setdefault("common", OrderedDict())
        sidebar = common.setdefault("sidebar", OrderedDict())
        sidebar["local"] = SIDEBAR_LOCAL[loc]

        save(path, data)
        print(f"{loc}: +{len(groups['eq'])} eq, +{len(groups['local'])} local, sidebar.local")

    print("all locales updated with full parity")


if __name__ == "__main__":
    main()
