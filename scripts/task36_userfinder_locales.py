for fname in sorted(os.listdir(LOCALES)):
    if not fname.endswith(".json"):
        continue
    path = os.path.join(LOCALES, fname)
    code = fname[:-5]
    section = SECTIONS.get(code)
    if section is None:
        print(f"SKIP {fname}: no translations")
        continue
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh, object_pairs_hook=collections.OrderedDict)
    settings = data.get("settings")
    if settings is None:
        print(f"SKIP {fname}: no settings section")
        continue
    if "user_finder" in settings:
        print(f"NOOP {fname}")
        continue
    # insert user_finder right after announcement (website-port grouping)
    new_settings = collections.OrderedDict()
    for k, v in settings.items():
        new_settings[k] = v
        if k == "announcement":
            new_settings["user_finder"] = collections.OrderedDict(
                sorted(section.items())
            )
    if "user_finder" not in new_settings:
        new_settings["user_finder"] = collections.OrderedDict(
            sorted(section.items())
        )
    data["settings"] = new_settings
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"OK {fname}")
